"""One runtime decision table for the planner and generated Inno Setup policy.

This module does not inspect the host OS, download a runtime, or build a package.
The caller must supply the actual Windows version and native OS architecture.
"""

from __future__ import annotations

from dataclasses import dataclass
from operator import eq, ge


_MAX_VERSION_COMPONENT = 65535
_ARCHITECTURE_CODES = {"x86": 0, "x64": 9, "arm64": 12}
_INVALID_VERSION = "系统版本信息无效：版本号及 Service Pack 必须是 0 至 65535 的整数。"
_UNKNOWN_ARCHITECTURE = "无法识别系统架构；只接受 x86、x64 或 ARM64 的检测结果。"
_UNSUPPORTED_OS = (
    "此安装包仅支持 Windows 7 SP1、Windows 8/8.1，"
    "以及 Windows 10 或更高版本的 x64 系统。"
)
_LEGACY_ARCHITECTURE_ERROR = (
    "Windows 7/8/8.1 兼容客户端仅支持 x86 或 x64，暂不支持 ARM64。"
)
_MODERN_ARCHITECTURE_ERROR = (
    "Windows 10 及以上沿用现有 x64 原生客户端；此安装包不支持 x86 或 ARM64。"
)
_WIN7_SERVICE_PACK_ERROR = (
    "Windows 7 需先安装 SP1。SP1 是本项目的验证基线，"
    "不是 Supermium 浏览器官方的硬性要求。"
)


@dataclass(frozen=True)
class _VersionPredicate:
    field: str
    comparison: str
    value: int

    def matches(self, version: dict[str, int]) -> bool:
        return {"=": eq, ">=": ge}[self.comparison](version[self.field], self.value)

    def pascal(self) -> str:
        return f"({self.field} {self.comparison} {self.value})"


@dataclass(frozen=True)
class _RuntimeRule:
    name: str
    version: tuple[_VersionPredicate, ...]
    minimum_service_pack: int
    runtimes: tuple[tuple[str, str], ...]
    architecture_error: str
    service_pack_error: str = ""

    def matches(self, version: dict[str, int]) -> bool:
        return all(predicate.matches(version) for predicate in self.version)

    def pascal_condition(self) -> str:
        return " and ".join(predicate.pascal() for predicate in self.version)


_LEGACY_RUNTIMES = (("x86", "legacy-x86"), ("x64", "legacy-x64"))
_DECISION_TABLE = (
    _RuntimeRule(
        "Windows 7 SP1",
        (_VersionPredicate("Major", "=", 6), _VersionPredicate("Minor", "=", 1)),
        1,
        _LEGACY_RUNTIMES,
        _LEGACY_ARCHITECTURE_ERROR,
        _WIN7_SERVICE_PACK_ERROR,
    ),
    _RuntimeRule(
        "Windows 8",
        (_VersionPredicate("Major", "=", 6), _VersionPredicate("Minor", "=", 2)),
        0,
        _LEGACY_RUNTIMES,
        _LEGACY_ARCHITECTURE_ERROR,
    ),
    _RuntimeRule(
        "Windows 8.1",
        (_VersionPredicate("Major", "=", 6), _VersionPredicate("Minor", "=", 3)),
        0,
        _LEGACY_RUNTIMES,
        _LEGACY_ARCHITECTURE_ERROR,
    ),
    _RuntimeRule(
        "Windows 10 and later",
        (_VersionPredicate("Major", ">=", 10),),
        0,
        (("x64", "native-x64"),),
        _MODERN_ARCHITECTURE_ERROR,
    ),
)


def selection_error(
    major: int, minor: int, service_pack_major: int, architecture: str
) -> str:
    """Return a Chinese rejection reason, or an empty string for supported input."""
    components = (major, minor, service_pack_major)
    if any(type(value) is not int or not 0 <= value <= _MAX_VERSION_COMPONENT for value in components):
        return _INVALID_VERSION
    if type(architecture) is not str or architecture not in _ARCHITECTURE_CODES:
        return _UNKNOWN_ARCHITECTURE
    version = {"Major": major, "Minor": minor}
    for rule in _DECISION_TABLE:
        if rule.matches(version):
            if service_pack_major < rule.minimum_service_pack:
                return rule.service_pack_error
            if architecture not in dict(rule.runtimes):
                return rule.architecture_error
            return ""
    return _UNSUPPORTED_OS


def select_runtime(
    major: int, minor: int, service_pack_major: int, architecture: str
) -> str:
    """Select the supported runtime without falling back across OS families."""
    error = selection_error(major, minor, service_pack_major, architecture)
    if error:
        raise ValueError(error)
    version = {"Major": major, "Minor": minor}
    for rule in _DECISION_TABLE:
        if rule.matches(version):
            return dict(rule.runtimes)[architecture]
    raise AssertionError("Validated Windows version has no runtime rule")


def _pascal_string(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _pascal_rejection(condition: str, error: str, indent: str = "  ") -> list[str]:
    return [
        f"{indent}if {condition} then",
        f"{indent}begin",
        f"{indent}  Result := {_pascal_string(error)};",
        f"{indent}  Exit;",
        f"{indent}end;",
    ]


def render_inno_policy() -> str:
    """Generate a Pascal fragment for an Inno Setup [Code] section.

    Architecture uses SYSTEM_INFO processor values: 0=x86, 9=x64, 12=ARM64.
    SelectRuntime returns an empty string for rejected input; callers should
    display RuntimeSelectionError before stopping installation.
    """
    parameters = "Major, Minor, ServicePackMajor, Architecture: Integer"
    lines = [
        "// Generated by runtime_policy.py. Do not maintain a second OS decision table.",
        f"function RuntimeSelectionError({parameters}): String;",
        "begin",
        "  Result := '';",
    ]
    invalid_version = " or ".join(
        f"({field} < 0) or ({field} > {_MAX_VERSION_COMPONENT})"
        for field in ("Major", "Minor", "ServicePackMajor")
    )
    lines.extend(_pascal_rejection(invalid_version, _INVALID_VERSION))
    unknown_architecture = " and ".join(
        f"(Architecture <> {code})" for code in _ARCHITECTURE_CODES.values()
    )
    lines.extend(_pascal_rejection(unknown_architecture, _UNKNOWN_ARCHITECTURE))
    for rule in _DECISION_TABLE:
        lines.extend([f"  // {rule.name}", f"  if {rule.pascal_condition()} then", "  begin"])
        if rule.minimum_service_pack:
            lines.extend(
                _pascal_rejection(
                    f"ServicePackMajor < {rule.minimum_service_pack}",
                    rule.service_pack_error,
                    "    ",
                )
            )
        allowed_architectures = " or ".join(
            f"(Architecture = {_ARCHITECTURE_CODES[architecture]})"
            for architecture, _ in rule.runtimes
        )
        lines.extend(
            [
                f"    if {allowed_architectures} then",
                "      Exit;",
                f"    Result := {_pascal_string(rule.architecture_error)};",
                "    Exit;",
                "  end;",
            ]
        )
    lines.extend([f"  Result := {_pascal_string(_UNSUPPORTED_OS)};", "end;", ""])
    lines.extend(
        [
            f"function SelectRuntime({parameters}): String;",
            "begin",
            "  Result := '';",
            "  if RuntimeSelectionError(Major, Minor, ServicePackMajor, Architecture) <> '' then",
            "    Exit;",
        ]
    )
    for rule in _DECISION_TABLE:
        lines.extend([f"  // {rule.name}", f"  if {rule.pascal_condition()} then", "  begin"])
        for architecture, runtime in rule.runtimes:
            lines.extend(
                [
                    f"    if Architecture = {_ARCHITECTURE_CODES[architecture]} then",
                    f"      Result := {_pascal_string(runtime)};",
                ]
            )
        lines.extend(["    Exit;", "  end;"])
    lines.extend(["end;", ""])
    return "\n".join(lines)
