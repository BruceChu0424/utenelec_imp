-- =====================================================================
-- V81：仓库增加「不良品仓」标记（即时库存「含不良品仓」开关）
-- =====================================================================
-- 老库 B_Storage 无不良仓标记字段（Remark 全空），只能按名称识别
-- （成品不良品仓 C0401 / 原材料不良仓 002）。老系统即时库存把它们算进「全部」
-- （IsCal=0 一视同仁）；新系统保留该默认，同时给用户「不含不良品仓」的开关。
-- =====================================================================

ALTER TABLE warehouses ADD COLUMN IF NOT EXISTS is_defective BOOLEAN NOT NULL DEFAULT FALSE;

-- 存量回填：按名称识别（老库无字段，仅此口径；迁移脚本同步同款规则，重跑一致）
UPDATE warehouses SET is_defective = TRUE WHERE name LIKE '%不良%';

COMMENT ON COLUMN warehouses.is_defective IS
    '不良品仓标记（老库无字段，按名称「不良」识别）；即时库存「全部」默认含，开关可剔除';
