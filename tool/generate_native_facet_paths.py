"""Generate the client read-only transport allow-list from the server's one authoritative route table."""
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'server/src/main/java/com/uten/imp/common/report/NativeFacetRoutes.java'
TARGET=ROOT/'lib/core/network/native_facet_routes.dart'

def generated():
    source=SOURCE.read_text(encoding='utf-8')
    paths=re.findall(r'add\(routes,\s*"(/api/[^"\r\n]+)"\s*,',source)
    if not paths or len(paths)!=len(set(paths)) or source.count('add(routes,')!=len(paths):
        raise ValueError('Every native candidate route must use one explicit unique literal')
    return ('// Generated by tool/generate_native_facet_paths.py from NativeFacetRoutes.java.\n'
            '// Edit the server route table and regenerate; this transport list grants no permission.\n'
            'const nativeFacetPaths = <String>{\n'+''.join(f"  '{path[4:]}',\n" for path in paths)+'};\n\n'
            'bool isNativeFacetPath(String path) => nativeFacetPaths.contains(\n'
            "  path.startsWith('/api/') ? path.substring(4) : path,\n);\n")

if __name__=='__main__':
    import sys
    result=generated()
    if '--check' in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8')!=result:
            raise SystemExit('Native facet client paths are stale; regenerate them')
    else:
        TARGET.write_text(result,encoding='utf-8',newline='\n')
