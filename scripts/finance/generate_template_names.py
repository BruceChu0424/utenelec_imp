"""Generate Flutter entry captions from the same source contract used by the server."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
source = root / 'server/src/main/resources/finance/template-contract-v1.json'
contract = json.loads(source.read_text(encoding='utf-8'))
lines = ['// Generated by scripts/finance/generate_template_names.py; edit the source contract.',
         'abstract final class FinanceRequirementNames {']
for key, item in contract['templates'].items():
    value = item['entryName'].replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
    lines.append(f"  static const {key} = '{value}';")
    if 'reportTitle' in item:
        title=item['reportTitle'].replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
        lines.append(f"  static const {key}Title = '{title}';")
lines.append('  static const chartClassificationLabels = <String, String>{')
for group in contract['templates']['chartCodes']['classifications']:
    lines.append(f"    '{group['id']}': '{group['label']}',")
lines += ['  };', '}', '']
target = root / 'lib/features/finance/config/finance_requirement_names.dart'
target.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
