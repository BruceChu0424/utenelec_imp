-- =====================================================================
-- V100：内部车间不再作为委外商可选（仓库部门需求·庞宗荣·高）
-- =====================================================================
-- 背景：老系统把内部车间当「委外机构」建模（suppliers 里的 铜柱车间/轨道车间/仪表车间）。
--   新系统车间 = 部门（departments 已有 五金铜柱车间/注塑车间/装配车间等），
--   且 V97 起仓库单据带「领料车间」字段，车间流转走部门通道，不再委外。
-- 设计：
--   suppliers.is_internal_workshop 标记内部车间——字典接口（单据选择器）排除，
--   主档列表/详情仍保留（5,720 张委外进仓 + 4,824 张委外发料历史单据引用，不可删）。
-- =====================================================================

ALTER TABLE suppliers
    ADD COLUMN IF NOT EXISTS is_internal_workshop BOOLEAN NOT NULL DEFAULT false;

UPDATE suppliers SET is_internal_workshop = true
WHERE name IN ('铜柱车间', '轨道车间', '仪表车间');
