// 进度比率归一（全站唯一启发式入口）。
//
// 服务端权威口径：进度/比率一律 0-1 且已 clamp 后下发，正常路径直接使用本函数返回值。
// 防御分支：值 >1 视为历史或手工录入的百分数（如 85 表示 85%），除以 100 归一。
// 各页面/模型不得再各自实现 `>1 ? /100` 判断——收敛至此一处（2026-08-16 复查收口）。

/// 把 [value] 归一为 0-1 比率；>1 时按百分数除以 100。
double normalizeProgressRatio(num value) =>
    value > 1 ? value / 100 : value.toDouble();
