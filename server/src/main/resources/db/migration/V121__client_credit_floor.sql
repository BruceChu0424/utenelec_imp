-- =====================================================================
-- V121：客户铺底额 + 应收/应付汇总表按附件 3/6 口径补全
-- =====================================================================
-- 背景（财务部门需求·王少春）：
--   应收账款汇总表（附件6）：结算期限 / 铺底额 / 上月余额 / 发货 / 回款 / 退货 / 冲销 /
--     应收余额 / 超出铺底额 / 物料金额——骨架已有（B 应收汇总），但铺底额/超铺底为 NULL 占位、
--     缺结算期限列；
--   应付账款汇总表（附件3）：按供应商汇总（结算期限/上月余额/货款/付款/退货/冲销/货款余额/
--     应付合计）——现 D 应付汇总是按立帐单号一行一单，需补按供应商口径。
-- 设计：
--   clients.credit_floor 铺底额（应收管控下限；超铺底 = 应收余额 − 铺底额，负取 0）。
--   结算期限列 = 结帐方式（PStyle 字典）+ TDay 天数渲染（服务端出文字，前端零改动）。
-- =====================================================================

ALTER TABLE clients
    ADD COLUMN IF NOT EXISTS credit_floor NUMERIC(18,4);

COMMENT ON COLUMN clients.credit_floor IS '铺底额（应收管控下限，元）；应收汇总表「超出铺底额」= 应收余额−铺底额';
