CREATE TABLE "WebsiteStateAuthority" (
    "id" TEXT NOT NULL PRIMARY KEY,
    "authorityUuid" TEXT NOT NULL,
    "mediaGeneration" INTEGER NOT NULL DEFAULT 0,
    "initializedAt" DATETIME,
    "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" DATETIME NOT NULL,
    CONSTRAINT "WebsiteStateAuthority_authorityUuid_check" CHECK (
        "authorityUuid" = 'UNBOUND' OR (
            length("authorityUuid") = 36
            AND substr("authorityUuid", 9, 1) = '-'
            AND substr("authorityUuid", 14, 1) = '-'
            AND substr("authorityUuid", 19, 1) = '-'
            AND substr("authorityUuid", 24, 1) = '-'
            AND lower("authorityUuid") = "authorityUuid"
            AND replace("authorityUuid", '-', '') NOT GLOB '*[^0-9a-f]*'
        )
    )
);

-- The UUID is deliberately not generated by a migration or discovered from a
-- mounted volume.  The root installer pins an operator-approved UUID and the
-- stopped activation transaction replaces this sentinel exactly once.
INSERT INTO "WebsiteStateAuthority" (
    "id", "authorityUuid", "mediaGeneration", "initializedAt", "createdAt", "updatedAt"
) VALUES (
    'production', 'UNBOUND', 0, NULL, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
);

