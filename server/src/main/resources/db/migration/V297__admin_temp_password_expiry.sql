-- =====================================================================
-- V297：管理员设置的临时密码增加 72 小时有效期
-- =====================================================================
-- 背景：权限设置页「账号安全」支持管理员为忘记密码的员工设置一次性临时密码
--   （重置后 must_change_password=true、全会话失效、明文仅展示一次）。
--   此前临时密码永久有效：员工长期不登录时，泄露的临时密码随时可被利用。
-- 设计：
--   temp_password_expires_at 仅由管理员 reset-password 流程写入（now + 72h）；
--   入职/补开账号的初始密码（证件号后 6 位）不写入，保持现有行为不变；
--   登录时若 must_change_password=true 且该列已过期 → 拒绝登录，
--   提示员工重新找管理员设置；员工改密成功后清空该列。
-- =====================================================================

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS temp_password_expires_at TIMESTAMPTZ NULL;

COMMENT ON COLUMN users.temp_password_expires_at IS
    '管理员设置的临时密码有效期截止时间（仅 admin reset-password 写入）；到期后临时密码不可再登录，员工改密成功后清空';
