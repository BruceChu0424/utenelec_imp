"""Installation policy and read-only payload checks for the native WPF pilot.

This does not build installers, fetch runtimes, modify the registry or publish.
The generated Pascal policy is checked in so the Inno template needs no Python.
No Windows 7 computer has been certified by these source-level checks.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import ipaddress
import json
from pathlib import Path
import struct
from urllib.parse import urlsplit

MIN_NET_RELEASE = 528040
SUPPORTED_WINDOWS = {(6, 1): 1, (6, 3): 0}
ARCHITECTURES = {0: "x86", 9: "x64"}
EXECUTABLE_NAME = "Uten.Legacy.Desktop.exe"
PROFILE_RELATIVE_PATH = r"Uten\UIMP-Win7-WPF"

ERRORS = {
    "server": "当前验证版仅支持 Windows 7 SP1 或 Windows 8.1 工作站系统。",
    "modern": "这台电脑请继续使用现有 Windows 10/11 客户端；当前兼容验证版不会安装。",
    "service_pack": "Windows 7 需要先安装 Service Pack 1；本安装器不会自动修改系统环境。",
    "os": "当前验证版仅支持 Windows 7 SP1 和 Windows 8.1；Windows 8.0 不支持本程序所需的 .NET Framework 4.8。",
    "architecture": "当前验证版仅提供 x86 和 x64；不支持 ARM 或无法识别的系统架构。",
    "framework": "需要先安装 Microsoft 官方 .NET Framework 4.8（Full）。请由管理员核对系统更新及官方安装要求；本安装器不会下载或安装系统组件。",
}


@dataclass(frozen=True)
class InstallDecision:
    architecture: str | None
    error: str | None


def decide_installation(
    major: int,
    minor: int,
    service_pack: int,
    processor_architecture: int,
    net_release: int | None,
    product_type: int = 1,
) -> InstallDecision:
    if product_type != 1:
        return InstallDecision(None, ERRORS["server"])
    if major >= 10:
        return InstallDecision(None, ERRORS["modern"])
    minimum_sp = SUPPORTED_WINDOWS.get((major, minor))
    if minimum_sp is None:
        return InstallDecision(None, ERRORS["os"])
    if service_pack < minimum_sp:
        return InstallDecision(None, ERRORS["service_pack"])
    architecture = ARCHITECTURES.get(processor_architecture)
    if architecture is None:
        return InstallDecision(None, ERRORS["architecture"])
    if net_release is None or net_release < MIN_NET_RELEASE:
        return InstallDecision(None, ERRORS["framework"])
    return InstallDecision(architecture, None)


def render_pascal_policy() -> str:
    """Render the policy facts used by the independent Inno installer."""
    def quoted(value: str) -> str:
        return "'" + value.replace("'", "''") + "'"

    lines = [
        "// Generated by wpf_install_policy.py; do not edit independently.",
        "// Microsoft version detection: Release >= 528040 means .NET 4.8 or later.",
        "function SelectWpfArchitecture(Major, Minor, ServicePackMajor,",
        "  Architecture, ProductType: Integer; NetRelease: Cardinal;",
        "  var ErrorMessage: String): String;",
        "begin",
        "  Result := '';",
        "  ErrorMessage := '';",
        "  if ProductType <> 1 then begin",
        f"    ErrorMessage := {quoted(ERRORS['server'])};",
        "    Exit;",
        "  end;",
        "  if Major >= 10 then begin",
        f"    ErrorMessage := {quoted(ERRORS['modern'])};",
        "    Exit;",
        "  end;",
    ]
    for index, ((major, minor), minimum_sp) in enumerate(SUPPORTED_WINDOWS.items()):
        prefix = "  if" if index == 0 else "  end else if"
        lines.append(f"{prefix} (Major = {major}) and (Minor = {minor}) then begin")
        if minimum_sp:
            lines.extend([
                f"    if ServicePackMajor < {minimum_sp} then begin",
                f"      ErrorMessage := {quoted(ERRORS['service_pack'])};",
                "      Exit;",
                "    end;",
            ])
    lines.extend([
        "  end else begin",
        f"    ErrorMessage := {quoted(ERRORS['os'])};",
        "    Exit;",
        "  end;",
        "  case Architecture of",
    ])
    for number, name in ARCHITECTURES.items():
        lines.append(f"    {number}: Result := {quoted(name)};")
    lines.extend([
        "  else begin",
        f"    ErrorMessage := {quoted(ERRORS['architecture'])};",
        "    Exit;",
        "  end;",
        "  end;",
        f"  if NetRelease < {MIN_NET_RELEASE} then begin",
        "    Result := '';",
        f"    ErrorMessage := {quoted(ERRORS['framework'])};",
        "  end;",
        "end;",
        "",
    ])
    return "\n".join(lines)


def inspect_managed_executable(path: Path, expected_architecture: str) -> dict[str, int | str]:
    """Reject native/AnyCPU/wrong-architecture files before payload assembly."""
    if expected_architecture not in ARCHITECTURES.values():
        raise ValueError("Only x86 and x64 are supported")
    if path.is_symlink() or not path.is_file():
        raise ValueError("Executable must be an ordinary file")
    data = path.read_bytes()

    def read(fmt: str, offset: int):
        size = struct.calcsize(fmt)
        if offset < 0 or offset + size > len(data):
            raise ValueError("Truncated PE executable")
        return struct.unpack_from(fmt, data, offset)

    if data[:2] != b"MZ":
        raise ValueError("Missing DOS header")
    pe_offset = read("<I", 0x3C)[0]
    if pe_offset < 0x40 or data[pe_offset:pe_offset + 4] != b"PE\0\0":
        raise ValueError("Missing PE signature")
    machine, section_count = read("<HH", pe_offset + 4)
    optional_size = read("<H", pe_offset + 20)[0]
    characteristics = read("<H", pe_offset + 22)[0]
    if not characteristics & 2 or characteristics & 0x2000:
        raise ValueError("Payload must be an executable image, not a DLL")
    optional = pe_offset + 24
    magic = read("<H", optional)[0]
    expected_machine, expected_magic = {
        "x86": (0x14C, 0x10B),
        "x64": (0x8664, 0x20B),
    }[expected_architecture]
    if (machine, magic) != (expected_machine, expected_magic):
        raise ValueError("PE machine or optional header differs from target architecture")
    directory_start = optional + (96 if magic == 0x10B else 112)
    directory_count = read("<I", directory_start - 4)[0]
    if directory_count <= 14 or optional_size < directory_start - optional + 15 * 8:
        raise ValueError("Missing CLR data directory")
    clr_rva, clr_size = read("<II", directory_start + 14 * 8)
    if not clr_rva or clr_size < 72:
        raise ValueError("Payload is not a managed .NET executable")
    section_table = optional + optional_size
    if not 1 <= section_count <= 96:
        raise ValueError("Invalid PE section count")
    clr_offset = None
    for index in range(section_count):
        section = section_table + index * 40
        virtual_size, virtual_address, raw_size, raw_offset = read("<IIII", section + 8)
        if virtual_address <= clr_rva < virtual_address + max(virtual_size, raw_size):
            delta = clr_rva - virtual_address
            if delta + 72 > raw_size:
                raise ValueError("CLR header is not backed by file bytes")
            clr_offset = raw_offset + delta
            break
    if clr_offset is None:
        raise ValueError("CLR header does not belong to a PE section")
    read("<72s", clr_offset)
    header_size, runtime_major, runtime_minor = read("<IHH", clr_offset)
    if header_size < 72:
        raise ValueError("Invalid CLR header size")
    flags = read("<I", clr_offset + 16)[0]
    if not flags & 1 or flags & 0x10:
        raise ValueError("Expected an IL-only managed entry point")
    if expected_architecture == "x86" and not flags & 2:
        raise ValueError("x86 payload must set 32BITREQUIRED; AnyCPU is not x86")
    if expected_architecture == "x64" and flags & (2 | 0x20000):
        raise ValueError("x64 payload has incompatible 32-bit CLR flags")
    return {
        "architecture": expected_architecture,
        "machine": machine,
        "clrFlags": flags,
        "clrHeaderMajor": runtime_major,
        "clrHeaderMinor": runtime_minor,
    }


def validate_app_configuration(path: Path) -> dict:
    """Check endpoint shape without contacting or trusting arbitrary services."""
    if path.is_symlink() or not path.is_file():
        raise ValueError("Configuration must be an ordinary JSON file")
    value = json.loads(path.read_text(encoding="utf-8-sig"))
    endpoints = value.get("endpoints") if isinstance(value, dict) else None
    if not isinstance(endpoints, list) or not endpoints:
        raise ValueError("Configuration requires endpoints")
    identities = set()
    for endpoint in endpoints:
        if not isinstance(endpoint, dict):
            raise ValueError("Endpoint must be an object")
        identity = endpoint.get("id")
        if not isinstance(identity, str) or not identity.strip() or identity in identities:
            raise ValueError("Endpoint IDs must be non-empty and unique")
        identities.add(identity)
        url = endpoint.get("apiBaseUrl")
        if not isinstance(url, str) or any(character.isspace() for character in url):
            raise ValueError("Endpoint must be an HTTPS URL")
        parsed = urlsplit(url)
        if (parsed.scheme != "https" or not parsed.hostname or parsed.username is not None
                or parsed.password is not None or parsed.query or parsed.fragment
                or parsed.path.rstrip("/") != "/api"):
            raise ValueError("Endpoint requires an HTTPS /api URL without credentials or query")
        host = parsed.hostname.lower().rstrip(".")
        if host == "localhost" or host.endswith(".localhost"):
            raise ValueError("Release configuration cannot use localhost")
        # Accessing port also rejects malformed or out-of-range port values.
        _ = parsed.port
        try:
            address = ipaddress.ip_address(host)
        except ValueError:
            address = None
            if all(part.isdigit() for part in host.split(".")):
                raise ValueError("Ambiguous numeric endpoint is not allowed")
        if address is not None:
            mapped = address.ipv4_mapped if isinstance(address, ipaddress.IPv6Address) else None
            if (address.is_loopback or address.is_unspecified
                    or mapped is not None and (mapped.is_loopback or mapped.is_unspecified)):
                raise ValueError("Release configuration cannot use loopback or unspecified addresses")
    if value.get("selectedEndpointId") not in identities:
        raise ValueError("Selected endpoint does not exist")
    return value


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-policy", action="store_true")
    parser.add_argument("--write-policy", action="store_true")
    parser.add_argument("--verify-executable", type=Path)
    parser.add_argument("--architecture", choices=tuple(ARCHITECTURES.values()))
    parser.add_argument("--configuration", type=Path)
    args = parser.parse_args()
    if args.check_policy and args.write_policy:
        parser.error("Choose a read-only check or explicit regeneration")
    if args.write_policy:
        Path(__file__).with_suffix(".iss").write_text(render_pascal_policy(), encoding="utf-8", newline="\n")
    if args.check_policy:
        include = Path(__file__).with_suffix(".iss")
        if include.read_text(encoding="utf-8") != render_pascal_policy():
            parser.error("Generated Inno policy differs from the shared policy")
    if args.verify_executable:
        if not args.architecture:
            parser.error("--architecture is required with --verify-executable")
        print(json.dumps(inspect_managed_executable(args.verify_executable, args.architecture)))
    if args.configuration:
        validate_app_configuration(args.configuration)
        print("Configuration shape checked; endpoint approval and TLS connectivity remain unverified.")
    if not (args.check_policy or args.write_policy or args.verify_executable or args.configuration):
        parser.print_help()


if __name__ == "__main__":
    main()
