CREATE TABLE "WebsiteMediaObject" (
    "publicPath" TEXT NOT NULL PRIMARY KEY,
    "authorityId" TEXT NOT NULL,
    "sha256" TEXT NOT NULL,
    "sizeBytes" INTEGER NOT NULL,
    "state" TEXT NOT NULL DEFAULT 'PENDING',
    "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" DATETIME NOT NULL,
    CONSTRAINT "WebsiteMediaObject_authorityId_fkey" FOREIGN KEY ("authorityId") REFERENCES "WebsiteStateAuthority" ("id") ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT "WebsiteMediaObject_publicPath_check" CHECK (
        "publicPath" LIKE '/uploads/%'
        AND length("publicPath") BETWEEN 11 AND 500
        AND instr("publicPath", '\\') = 0
        AND instr("publicPath", '//') = 0
        AND instr("publicPath", '/./') = 0
        AND instr("publicPath", '/../') = 0
        AND instr("publicPath", '?') = 0
        AND instr("publicPath", '#') = 0
        AND instr("publicPath", '%') = 0
        AND instr("publicPath", char(9)) = 0
        AND instr("publicPath", char(10)) = 0
        AND instr("publicPath", char(13)) = 0
        AND instr("publicPath", ' ') = 0
        AND substr("publicPath", -2) != '/.'
        AND substr("publicPath", -3) != '/..'
    ),
    CONSTRAINT "WebsiteMediaObject_sha256_check" CHECK (
        length("sha256") = 64
        AND "sha256" NOT GLOB '*[^0-9a-f]*'
    ),
    CONSTRAINT "WebsiteMediaObject_sizeBytes_check" CHECK ("sizeBytes" > 0),
    CONSTRAINT "WebsiteMediaObject_state_check" CHECK ("state" IN ('PENDING', 'COMMITTED'))
);

-- Deterministic bootstrap for already audited legacy media.  Other CMS uploads
-- are reconciled by the stopped authority-initialization gate; nothing is
-- inferred from filenames and no business reference is rewritten here.
INSERT INTO "WebsiteMediaObject" (
    "publicPath", "authorityId", "sha256", "sizeBytes", "state", "createdAt", "updatedAt"
)
SELECT
    "publicPath", 'production', lower("sha256"), "bytes", 'COMMITTED', "createdAt", "updatedAt"
FROM "LegacyMediaAsset"
WHERE "publicPath" LIKE '/uploads/%';

