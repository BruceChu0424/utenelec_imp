-- Actual production stays on its original execution/cost source. The allowance
-- classifies this physical batch; it never truncates the quantity or creates a second plan.
ALTER TABLE production_daily_report_items
    ADD COLUMN is_over_limit BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN over_limit_reason TEXT,
    ADD COLUMN overproduction_authorization_snapshot JSONB,
    ADD CONSTRAINT daily_report_over_limit_shape CHECK (
        (NOT is_over_limit AND over_limit_reason IS NULL)
        OR (is_over_limit AND is_actual_surplus AND is_public_output
            AND output_batch_id IS NOT NULL AND destination='WAREHOUSE'
            AND over_limit_reason IS NOT NULL AND length(btrim(over_limit_reason)) BETWEEN 2 AND 500)),
    ADD CONSTRAINT daily_report_overproduction_snapshot_shape CHECK (
        overproduction_authorization_snapshot IS NULL
        OR (is_actual_surplus AND fqc_recovery_authorization_id IS NULL
            AND jsonb_typeof(overproduction_authorization_snapshot)='object'
            AND overproduction_authorization_snapshot->>'version'='1'));

CREATE INDEX idx_daily_report_over_limit ON production_daily_report_items(report_id,execution_segment_id)
    WHERE is_over_limit AND NOT is_deleted;

ALTER TABLE production_daily_report_items
