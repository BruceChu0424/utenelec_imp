-- A full media verification reads one generation before and after its
-- filesystem scan.  These signed-schema triggers make every relevant DB-side
-- ledger or business-reference mutation observable without coupling the
-- verifier to application code paths.
CREATE TRIGGER "WebsiteMediaObject_media_generation_insert"
AFTER INSERT ON "WebsiteMediaObject"
BEGIN
    UPDATE "WebsiteStateAuthority"
    SET "mediaGeneration" = "mediaGeneration" + 1, "updatedAt" = CURRENT_TIMESTAMP
    WHERE "id" = 'production';
END;

CREATE TRIGGER "WebsiteMediaObject_media_generation_update"
AFTER UPDATE ON "WebsiteMediaObject"
BEGIN
    UPDATE "WebsiteStateAuthority"
    SET "mediaGeneration" = "mediaGeneration" + 1, "updatedAt" = CURRENT_TIMESTAMP
    WHERE "id" = 'production';
END;

